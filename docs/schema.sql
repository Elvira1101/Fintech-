-- Schéma logique account-service (base H2 dédiée)
CREATE TABLE accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(22) NOT NULL UNIQUE,
    owner_email VARCHAR(160) NOT NULL,
    type VARCHAR(16) NOT NULL CHECK (type IN ('CURRENT', 'SAVINGS')),
    balance DECIMAL(19, 2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    version BIGINT
);
CREATE INDEX idx_accounts_owner_email ON accounts (owner_email);

-- Schéma logique transaction-service (base H2 dédiée).
-- Les identifiants de compte référencent account-service sans FK interbase.
CREATE TABLE bank_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(16) NOT NULL CHECK (type IN ('TRANSFER', 'DEPOSIT')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('ACCEPTED', 'SUSPICIOUS', 'BLOCKED')),
    source_account_id BIGINT,
    target_account_id BIGINT NOT NULL,
    amount DECIMAL(19, 2) NOT NULL CHECK (amount > 0),
    country VARCHAR(2) NOT NULL,
    owner_email VARCHAR(160) NOT NULL,
    fraud_reason VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_transactions_owner_created ON bank_transactions (owner_email, created_at DESC);
CREATE INDEX idx_transactions_source ON bank_transactions (source_account_id);
CREATE INDEX idx_transactions_target ON bank_transactions (target_account_id);